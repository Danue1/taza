//! 단모음을 이어 쳐서 복합 모음을 만드는 표 — 나랏글과 베가가 나눠 갖는다. 두 방식은
//! 단모음에 닿는 길만 다르고(획 추가와 멀티탭) 그 뒤의 조합 규칙이 하나이므로, 표를
//! 방식마다 적으면 한쪽만 고쳐지는 드리프트가 생긴다.
//!
//! 두벌식 오토마타의 모음 결합(`jamo::combine_jungseong`)과 나눠 갖지 않는 까닭은
//! 천지인과 같다: 두벌식에서 ㅏ 뒤의 ㅣ는 새 글자지만 이 방식들에서는 ㅐ다. 한 표로 둘을
//! 겸하면 둘 중 하나가 틀린다.

/// 모음 타건 순서 → 모음. 쌓인 타건 **전체**를 키로 삼으므로 늘어나는 도중의 모음이
/// 다음 모음을 가리지 않는다(ㅗㅏ는 ㅘ이고 ㅗㅏㅣ는 ㅙ다). 표의 키에 ㅑ·ㅕ·ㅛ·ㅠ가
/// 그대로 서는 것은, 그 모음에 닿는 길이 방식마다 달라도 여기 들어올 때는 이미 모음
/// 하나이기 때문이다.
const VOWELS: [(&str, char); 21] = [
    ("ㅏ", 'ㅏ'),
    ("ㅏㅣ", 'ㅐ'),
    ("ㅑ", 'ㅑ'),
    ("ㅑㅣ", 'ㅒ'),
    ("ㅓ", 'ㅓ'),
    ("ㅓㅣ", 'ㅔ'),
    ("ㅕ", 'ㅕ'),
    ("ㅕㅣ", 'ㅖ'),
    ("ㅗ", 'ㅗ'),
    ("ㅗㅏ", 'ㅘ'),
    ("ㅗㅏㅣ", 'ㅙ'),
    ("ㅗㅣ", 'ㅚ'),
    ("ㅛ", 'ㅛ'),
    ("ㅜ", 'ㅜ'),
    ("ㅜㅓ", 'ㅝ'),
    ("ㅜㅓㅣ", 'ㅞ'),
    ("ㅜㅣ", 'ㅟ'),
    ("ㅠ", 'ㅠ'),
    ("ㅡ", 'ㅡ'),
    ("ㅡㅣ", 'ㅢ'),
    ("ㅣ", 'ㅣ'),
];

/// 쌓인 타건이 이룬 모음. 어느 모음도 이루지 못하면 None — 그 타건에서 새 모음이 선다.
pub(super) fn vowel(taps: &[char]) -> Option<char> {
    let typed: String = taps.iter().collect();
    VOWELS
        .iter()
        .find(|&&(sequence, _)| sequence == typed)
        .map(|&(_, vowel)| vowel)
}
